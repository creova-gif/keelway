#!/usr/bin/env bash
# Verify requirements.lock is fresh against pyproject.toml.
# Regenerates the lock with the same command and diffs the pinned content.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

if ! command -v uv >/dev/null 2>&1; then
    echo "uv not found on PATH; skipping Python lock freshness check."
    exit 0
fi

TMP_LOCK="$(mktemp -t keelway-lock.XXXXXX)"
trap 'rm -f "${TMP_LOCK}"' EXIT

# --universal makes the resolution interpreter-independent, so this check
# produces identical output on every CI leg (3.11/3.14, Linux/macOS).
uv pip compile pyproject.toml --extra dev --extra postgres --generate-hashes --universal -o "${TMP_LOCK}"

# Ignore the autogenerated command header (first two lines) which embeds the
# output path, and `# via` comment lines — the dependency-graph annotations
# can legitimately differ across host interpreters even when pins, hashes,
# and env markers are identical.
if diff -u \
    <(tail -n +3 requirements.lock | grep -vE '^\s*#') \
    <(tail -n +3 "${TMP_LOCK}" | grep -vE '^\s*#'); then
    echo "requirements.lock is fresh."
else
    echo "requirements.lock is stale — regenerate with:" >&2
    echo "  uv pip compile pyproject.toml --extra dev --extra postgres --generate-hashes --universal -o requirements.lock" >&2
    exit 1
fi
