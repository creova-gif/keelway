"""Host-specific hook/plugin config templates for agent_coharness.

Separated from agent_coharness.py to keep that module under the
480-line engineering cap. Templates embed the workspace ID and mode;
all policy decisions still flow through `intercept_tool_call`.
"""

from __future__ import annotations


def build_opencode_plugin_content(ws: str, mode: str) -> str:
    """TypeScript plugin for OpenCode's `tool.execute.before` hook.

    OpenCode plugins run inside the agent's Bun runtime; there is no
    stdin-JSON shell-hook protocol. The plugin shells out to
    `keelway harness agents intercept` synchronously per tool call and
    throws to abort DENY/HOLD verdicts (fail-closed on CLI errors).
    """
    return f'''// Keelway Guard — generated by `keelway harness agents setup --agent opencode`.
// Policy authority: `keelway harness agents intercept` (agent co-harness).
// Mode: {mode} | Workspace: {ws}
// Regenerate: keelway harness agents setup --agent opencode --mode {mode} --install-dir .

const KEELWAY_BIN = process.env.KEELWAY_BIN || "keelway";
const KEELWAY_MODE = "{mode}";
const KEELWAY_WORKSPACE = "{ws}";

function keelwayIntercept(tool: string, args: unknown, sessionID?: string, callID?: string) {{
  const payload = JSON.stringify({{
    tool,
    tool_input: (args && typeof args === "object") ? args : {{}},
    session_id: sessionID || null,
    call_id: callID || null,
  }});
  const proc = Bun.spawnSync([
    KEELWAY_BIN, "harness", "agents", "intercept",
    "--agent", "opencode", "--payload", "-",
    "--mode", KEELWAY_MODE, "--workspace", KEELWAY_WORKSPACE,
    "--format", "json",
  ], {{
    stdin: new TextEncoder().encode(payload),
    stdout: "pipe",
    stderr: "pipe",
  }});
  // Exit codes: 0=allow, 1=deny, 2=hold(P-10); anything else is a check failure.
  if (proc.exitCode !== 0 && proc.exitCode !== 1 && proc.exitCode !== 2) {{
    throw new Error(`keelway policy check failed (exit ${{proc.exitCode}}): ${{proc.stderr.toString().slice(0, 300)}}`);
  }}
  let decision = "";
  let verdict = "";
  let reason = "";
  let ticketId: string | null = null;
  try {{
    const res = JSON.parse(proc.stdout.toString());
    decision = String(res.decision || "");
    const rec = res.record || {{}};
    verdict = String(rec.verdict || "");
    reason = String(rec.reason_code || "");
    ticketId = rec.ticket_id || null;
  }} catch {{
    throw new Error("keelway policy check returned unparseable output");
  }}
  if (KEELWAY_MODE === "audit_only") {{
    return; // evidence recorded; never block in audit mode
  }}
  if (decision === "deny" || verdict.startsWith("DENY")) {{
    throw new Error(`keelway policy DENY (${{reason || "unspecified"}})`);
  }}
  if (decision === "hold" || verdict.startsWith("HOLD")) {{
    throw new Error(`keelway P-10 approval required${{ticketId ? ` (ticket ${{ticketId}})` : ""}} — approve via keelway harness tickets`);
  }}
}}

export const KeelwayGuard = async () => {{
  return {{
    "tool.execute.before": async (input: {{ tool: string; sessionID?: string; callID?: string }}, output: {{ args?: unknown }}) => {{
      keelwayIntercept(input.tool, output.args, input.sessionID, input.callID);
    }},
    "tool.execute.after": async (input: {{ tool: string; sessionID?: string; callID?: string }}, output: {{ args?: unknown }}) => {{
      // PostToolUse lifecycle evidence (observational; no verdict).
      try {{
        const payload = JSON.stringify({{ tool: input.tool, tool_input: (output.args && typeof output.args === "object") ? output.args : {{}}, session_id: input.sessionID || null, call_id: input.callID || null }});
        Bun.spawnSync([KEELWAY_BIN, "harness", "agents", "event", "--agent", "opencode", "--event", "posttooluse", "--payload", "-", "--workspace", KEELWAY_WORKSPACE], {{ stdin: new TextEncoder().encode(payload), stdout: "ignore", stderr: "ignore" }});
      }} catch {{ /* evidence is best-effort; never block the agent */ }}
    }},
  }};
}};
'''


